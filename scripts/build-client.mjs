#!/usr/bin/env node
/**
 * build-client: produce the lazy-CJS browser artifact dsh/client.js.
 *
 * Two steps:
 *   1. esbuild bundles the browser card entry to the CJS intermediate
 *      dsh/.build/client.cjs. react and @deepseek-ai/dsh-client-ui-primitives
 *      stay external: they resolve at runtime through the shell's frozen
 *      platform module table, so the bundle must emit exactly those two
 *      runtime requires.
 *   2. The intermediate is wrapped in the window.__ModuleLoader__.load
 *      contract and written to dsh/client.js. esbuild's CJS external shim
 *      resolves `require` dynamically, so inside the factory it picks up the
 *      injected platform-table require.
 *
 * Run after `tsc -b` (the root build script chains the two). The output is
 * deterministic: a second run writes a byte-identical dsh/client.js.
 *
 * The bundle is REQUIRED (TASK-052): the browser card is a shipped half of
 * the install (root package.json files list and the dsh.client manifest
 * block), so a missing card entry or a failed esbuild pass fails the build
 * here, and scripts/verify-emit.mjs always asserts the artifact exists and
 * is non-empty. The ModuleLoader id is the root package.json "name" (the
 * bare package the client-module scan keys dsh.client on), matching
 * dsh-plugin-local-infer's convention.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import esbuild from 'esbuild'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const entry = join(root, 'packages/client/src/index.ts')
const intermediate = join(root, 'dsh/.build/client.cjs')
const artifact = join(root, 'dsh/client.js')

// The ModuleLoader id must equal the bare package name the client-module
// scan keys dsh.client on; reading it from package.json keeps the artifact
// correct through a rename instead of drifting silently.
const { name: loaderId } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

// Classic JSX transform (jsxFactory / jsxFragment): the automatic runtime
// (react/jsx-runtime) is not in the shell's platform module table.
await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react', '@deepseek-ai/dsh-client-ui-primitives'],
  outfile: intermediate,
  jsx: 'transform',
  jsxFactory: 'react.createElement',
  jsxFragment: 'react.Fragment',
})

const bundle = readFileSync(intermediate, 'utf8')
const output = `// generated by scripts/build-client.mjs. Do not edit.
window.__ModuleLoader__.load({ id: '${loaderId}', factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${bundle}
    return module.exports;
} });
`
writeFileSync(artifact, output)
console.log(`wrote dsh/client.js (${output.length} bytes)`)
